declare(strict_types=1);

/*
 * Writes the generated code from proto/api.proto and proto/proxy.proto: the
 * request and result types of every Centrifugo server API method, the client's
 * API methods, and the requests and results of the proxy protocol.
 *
 *     php gen/generate.php            # write generated/
 *     php gen/generate.php --check    # fail when generated/ is stale
 *
 * The output is committed, formatted with the project's php-cs-fixer rules.
 * `composer generate-check` runs the check in CI.
 */

namespace Centrifugal\Phpcent\Gen;

require_once __DIR__ . '/Proto.php';

const ROOT = __DIR__ . '/..';

// rpc calls server API extensions, which neither Centrifugo OSS nor PRO
// provides.
const OMITTED_COMMANDS = ['rpc'];

// Messages written by hand (BroadcastResult: a result per channel; Error: an
// exception), only used on the wire (the batch envelope), or wrappers which
// become nullable scalars.
const HANDWRITTEN = ['Error', 'BroadcastResult'];
const WIRE_ONLY = ['Command', 'Reply', 'BatchRequest', 'BatchResponse'];
const WRAPPERS = ['BoolValue' => 'bool', 'Int32Value' => 'int'];

const PHP_TYPES = [
    'string' => ['string', "''"],
    'bool' => ['bool', 'false'],
    'int32' => ['int', '0'],
    'int64' => ['int', '0'],
    'uint32' => ['int', '0'],
    'uint64' => ['int', '0'],
    'double' => ['float', '0.0'],
    'float' => ['float', '0.0'],
];

const HEADER = "<?php\n\n// Code generated by gen/generate.php from proto/%s. DO NOT EDIT.\n\ndeclare(strict_types=1);\n\nnamespace %s;\n";

final class Command
{
    public function __construct(
        public readonly string $method,
        public readonly ProtoMessage $request,
        public readonly string $result,
        public readonly bool $proOnly,
    ) {}
}

function camel(string $snake): string
{
    return lcfirst(str_replace('_', '', ucwords($snake, '_')));
}

/** @return list<Command> */
function commands(Proto $s): array
{
    $cmd = $s->byName['Command'] ?? null;
    $reply = $s->byName['Reply'] ?? null;
    if ($cmd === null || $reply === null) {
        throw new \RuntimeException('api.proto: Command and Reply messages are required');
    }
    $results = [];
    foreach ($reply->fields as $f) {
        $results[$f->name] = $f->type;
    }
    $out = [];
    foreach ($cmd->fields as $f) {
        if (\in_array($f->name, OMITTED_COMMANDS, true)) {
            continue;
        }
        $req = $s->byName[$f->type] ?? null;
        if ($req === null || !isset($results[$f->name])) {
            throw new \RuntimeException("api.proto: Command.{$f->name} has no request message or no Reply.{$f->name}");
        }
        $want = str_replace('_', '', ucwords($f->name, '_')) . 'Request';
        if (strtolower($f->type) !== strtolower($want)) {
            throw new \RuntimeException("api.proto: Command.{$f->name} is {$f->type}, expected {$want}");
        }
        $out[] = new Command($f->name, $req, $results[$f->name], str_contains(implode(' ', $f->doc), 'Centrifugo PRO only'));
    }

    return $out;
}

/** @return array<string, true> */
function skipped(Proto $s): array
{
    $names = array_fill_keys([...HANDWRITTEN, ...WIRE_ONLY, ...array_keys(WRAPPERS)], true);
    foreach ($s->methods as $rpc) {
        $names[$rpc->response] = true; // the error-or-result envelopes
    }
    foreach (['Command', 'Reply'] as $c) {
        foreach ($s->byName[$c]->fields as $f) {
            if (\in_array($f->name, OMITTED_COMMANDS, true)) {
                $names[$f->type] = true;
            }
        }
    }

    return $names;
}

/**
 * Whether the proto marks the field plainly "Required." - a required
 * parameter then. "Required unless ..." stays optional.
 */
function required(ProtoField $f): bool
{
    return preg_match('/\bRequired\./', implode(' ', $f->doc)) === 1;
}

/** A field's native type, its PHPDoc type, and its default. */
function fieldType(ProtoField $f): array
{
    $t = $f->type;
    if (isset(WRAPPERS[$t])) {
        [$base, $doc, $default] = ['?' . WRAPPERS[$t], WRAPPERS[$t] . '|null', 'null'];
    } elseif ($t === 'bytes') {
        [$base, $doc, $default] = ['mixed', 'mixed', 'null'];
    } elseif (isset(PHP_TYPES[$t])) {
        [$base, $default] = PHP_TYPES[$t];
        $doc = $base;
    } else {
        [$base, $doc, $default] = ["?{$t}", "{$t}|null", 'null'];
    }
    $inner = ltrim(str_replace('|null', '', $doc), '?');
    if ($f->mapKey !== '') {
        return ['array', "array<string, {$inner}>", '[]'];
    }
    if ($f->repeated) {
        return ['array', "list<{$inner}>", '[]'];
    }

    return [$base, $doc, $default];
}

/** Lines of toJson adding the field to $p when it is not its zero value. */
function encoder(ProtoField $f): array
{
    $n = '$this->' . camel($f->name);
    $key = var_export('"' . $f->name . '":', true);
    $path = "\$path . '{$f->name}'";
    $t = $f->type;
    if ($f->mapKey !== '' || $f->repeated) {
        $kind = $f->mapKey !== '' ? 'Map' : 'List';
        if ($t === 'bytes') {
            $value = "Encode::payload{$kind}({$n}, {$path})";
        } elseif ($t === 'string') {
            $value = "Encode::string{$kind}({$n}, {$path})";
        } elseif (isset(PHP_TYPES[$t])) {
            $value = 'Encode::' . PHP_TYPES[$t][0] . "{$kind}({$n}, {$path})";
        } else {
            $value = "Encode::message{$kind}({$n}, {$path})";
        }

        return ["if ({$n} !== []) {", "    \$p[] = {$key} . {$value};", '}'];
    }
    if (isset(WRAPPERS[$t])) {
        $v = WRAPPERS[$t] === 'bool' ? "({$n} ? 'true' : 'false')" : "(string) {$n}";

        return ["if ({$n} !== null) {", "    \$p[] = {$key} . '{\"value\":' . {$v} . '}';", '}'];
    }
    if ($t === 'bytes') {
        return ["if ({$n} !== null) {", "    \$p[] = {$key} . Encode::payload({$n}, {$path});", '}'];
    }
    if ($t === 'string') {
        return ["if ({$n} !== '') {", "    \$p[] = {$key} . Encode::string({$n}, {$path});", '}'];
    }
    if ($t === 'bool') {
        return ["if ({$n}) {", "    \$p[] = {$key} . 'true';", '}'];
    }
    if (isset(PHP_TYPES[$t]) && PHP_TYPES[$t][0] === 'int') {
        return ["if ({$n} !== 0) {", "    \$p[] = {$key} . {$n};", '}'];
    }
    if (isset(PHP_TYPES[$t])) {
        return ["if ({$n} !== 0.0) {", "    \$p[] = {$key} . Encode::float({$n}, {$path});", '}'];
    }

    // A nested message, left out when nothing in it is set.
    $var = '$' . camel($f->name) . 'Json';

    return [
        "if ({$n} !== null && ({$var} = {$n}->toJson({$path} . '.')) !== '{}') {",
        "    \$p[] = {$key} . {$var};",
        '}',
    ];
}

/** The expression of fromWire decoding the field from the object $d. */
function decoder(ProtoField $f): string
{
    $key = var_export($f->name, true);
    $t = $f->type;
    if (isset(WRAPPERS[$t])) {
        return 'Decode::' . (WRAPPERS[$t] === 'bool' ? 'boolValue' : 'int32Value') . "(\$d, {$key}, \$path)";
    }
    if (isset(PHP_TYPES[$t]) || $t === 'bytes') {
        $conv = $t === 'bytes' ? 'Decode::asPayload(...)' : 'Decode::as' . ucfirst(PHP_TYPES[$t][0]) . '(...)';
    } else {
        $conv = "{$t}::fromWire(...)";
    }
    if ($f->mapKey !== '') {
        return "Decode::mapOf(\$d, {$key}, \$path, {$conv})";
    }
    if ($f->repeated) {
        return "Decode::listOf(\$d, {$key}, \$path, {$conv})";
    }
    if ($t === 'bytes') {
        return "Decode::payload(\$d, {$key})";
    }
    if (isset(PHP_TYPES[$t])) {
        return 'Decode::' . PHP_TYPES[$t][0] . "(\$d, {$key}, \$path)";
    }

    return "Decode::message(\$d, {$key}, \$path, {$conv})";
}

/**
 * A field's proto comment as PHPDoc: the proto's comments begin with the field's
 * name, as Go's do - "skip_history skips adding..." - which a PHPDoc @param
 * does not repeat: "Skips adding...". "data is the payload" becomes "The
 * payload"; "version, when > 0, is the version" becomes "When > 0, the
 * version". When the name is followed by anything else, it is written as the
 * PHP parameter instead.
 *
 * @return list<string>
 */
function fieldDoc(ProtoMessage $m, ProtoField $f): array
{
    $lines = $f->doc;
    if ($lines !== []) {
        $first = $lines[0];
        $name = preg_quote($f->name, '/');
        if (preg_match("/^`?{$name}`?\\s+(?:is|are)\\s+(.*)$/", $first, $mm) === 1) {
            $lines[0] = ucfirst($mm[1]);
        } elseif (preg_match("/^`?{$name}`?\\s+([a-z].*)$/", $first, $mm) === 1) {
            $lines[0] = ucfirst($mm[1]);
        } elseif (preg_match("/^`?{$name}`?,\\s*(.+?),\\s+(?:(?:is|are)\\s+)?(.*)$/", $first, $mm) === 1) {
            // "version, when > 0, is the version..." -> "When > 0, the version..."
            $lines[0] = ucfirst($mm[1]) . ', ' . $mm[2];
        } elseif (preg_match("/^`?{$name}`?(\\W.*)$/", $first, $mm) === 1) {
            $lines[0] = '$' . camel($f->name) . $mm[1];
        }
    }

    return fieldRefs($m, $lines);
}

/**
 * Mentions of the message's fields in comment lines written as the PHP
 * parameters: `data` and version_epoch become $data and $versionEpoch. A bare
 * name is taken for a field only when it cannot be an English word - it has an
 * underscore or a digit - so that "binary data" stays prose.
 *
 * @param list<string> $lines
 *
 * @return list<string>
 */
function fieldRefs(ProtoMessage $m, array $lines): array
{
    global $schema;
    if ($schema instanceof Proto) {
        // SubscribeRequest.all_users -> SubscribeRequest::$allUsers.
        $lines = array_map(static fn(string $l): string => preg_replace_callback(
            '/\\b([A-Z]\\w*)\\.([a-z][a-z0-9_]*)\\b/',
            static function (array $mm) use ($schema): string {
                foreach ($schema->byName[$mm[1]]->fields ?? [] as $g) {
                    if ($g->name === $mm[2]) {
                        return $mm[1] . '::$' . camel($g->name);
                    }
                }

                return $mm[0];
            },
            $l,
        ) ?? $l, $lines);
        // A field of another message, by a name which cannot be a word.
        $names = [];
        foreach ($schema->messages as $other) {
            foreach ($other->fields as $g) {
                if (preg_match('/[_0-9]/', $g->name) === 1) {
                    $names[$g->name] = '$' . camel($g->name);
                }
            }
        }
        foreach ($names as $name => $camel) {
            $pattern = '/(?<![\\w$.\\/:-])' . preg_quote($name, '/') . '(?![\\w\\/-])/';
            $lines = array_map(static fn(string $l): string => preg_replace($pattern, $camel, $l) ?? $l, $lines);
        }
    }
    foreach ($m->fields as $g) {
        $camel = '$' . camel($g->name);
        $lines = array_map(static fn(string $l): string => str_replace('`' . $g->name . '`', $camel, $l), $lines);
        if (preg_match('/[_0-9]/', $g->name) === 1) {
            $pattern = '/(?<![\\w$.\/-])' . preg_quote($g->name, '/') . '(?![\\w\/-])/';
            $lines = array_map(static fn(string $l): string => preg_replace($pattern, $camel, $l) ?? $l, $lines);
        }
    }

    return $lines;
}

/** Proto comment lines as PHPDoc text: safe inside a docblock. */
function docText(array $lines): array
{
    return array_map(static function (string $l): string {
        $l = str_replace('*/', '*&#47;', $l);

        return str_starts_with($l, '@') ? '\\' . $l : $l;
    }, $lines);
}

function docblock(array $lines, string $indent): string
{
    $lines = array_values($lines);
    if ($lines === []) {
        return '';
    }
    $out = "{$indent}/**\n";
    foreach ($lines as $l) {
        $out .= rtrim("{$indent} * {$l}") . "\n";
    }

    return $out . "{$indent} */\n";
}

function methodDoc(Command $c): array
{
    $doc = $c->request->doc;
    $prefix = $c->request->name . ' ';
    if ($doc !== [] && str_starts_with($doc[0], $prefix)) {
        $rest = substr($doc[0], \strlen($prefix));
        $doc[0] = ucfirst($rest);
    }
    if ($doc === []) {
        $doc = ["Calls the {$c->method} method of the Centrifugo server API."];
    }
    if ($c->proOnly && !str_contains(implode(' ', $doc), 'Centrifugo PRO only')) {
        $doc[] = 'Centrifugo PRO only.';
    }

    return docText(fieldRefs($c->request, $doc));
}

function emitMessage(ProtoMessage $m, string $namespace, string $proto, string $protocol, ?Command $command): string
{
    $out = \sprintf(HEADER, $proto, $namespace) . "\n";
    $uses = [];
    if ($namespace !== 'Centrifugal\\Phpcent\\Internal') {
        $uses = ['Centrifugal\\Phpcent\\Internal\\Decode', 'Centrifugal\\Phpcent\\Internal\\Encode'];
    }
    if ($namespace !== 'Centrifugal\\Phpcent') {
        $uses[] = 'Centrifugal\\Phpcent\\Message';
        $uses[] = 'Centrifugal\\Phpcent\\RawJson';
    }
    if ($command !== null) {
        // A request is internal: the types of its fields and its result are
        // the root namespace's - php-cs-fixer drops the imports left unused.
        $uses[] = 'Centrifugal\\Phpcent\\' . ($command->method === 'broadcast' ? 'BroadcastResult' : $command->result);
        foreach ($m->fields as $f) {
            if (!isset(PHP_TYPES[$f->type]) && !isset(WRAPPERS[$f->type]) && $f->type !== 'bytes') {
                $uses[] = 'Centrifugal\\Phpcent\\' . $f->type;
            }
        }
        $uses = array_values(array_unique($uses));
    }
    sort($uses);
    foreach ($uses as $u) {
        $out .= "use {$u};\n";
    }
    $out .= "\n";

    $doc = docText(fieldRefs($m, $m->doc !== [] ? $m->doc : ["{$m->name} is the {$m->name} message of the Centrifugo {$protocol}."]));
    $result = $command?->method === 'broadcast' ? 'BroadcastResult' : $command?->result;
    if ($command !== null) {
        $doc[] = '';
        $doc[] = "@implements Request<{$result}>";
        $doc[] = '';
        $doc[] = '@internal the client, Batch and Command build it from their named arguments';
    }
    $out .= docblock($doc, '');
    $out .= 'final class ' . $m->name . ' implements Message' . ($command !== null ? ', Request' : '') . "\n{\n";

    if ($command !== null) {
        $out .= "    /** The server API method the request is sent to. */\n";
        $out .= "    public const string API_METHOD = '{$command->method}';\n\n";
    }

    // The constructor: every field a promoted property, named arguments.
    if ($m->fields === []) {
        $out .= "    public function __construct() {}\n";
    } else {
        $params = [];
        foreach ($m->fields as $f) {
            [, $docType] = fieldType($f);
            $text = docText(fieldDoc($m, $f));
            $params[] = "@param {$docType} \$" . camel($f->name) . ($text !== [] ? ' ' . array_shift($text) : '');
            foreach ($text as $t) {
                $params[] = '    ' . $t;
            }
        }
        $out .= docblock($params, '    ');
        $out .= "    public function __construct(\n";
        foreach ($m->fields as $f) {
            [$type, , $default] = fieldType($f);
            $out .= "        public {$type} \$" . camel($f->name) . " = {$default},\n";
        }
        $out .= "    ) {}\n";
    }

    if ($command !== null) {
        $out .= "\n    public static function apiMethod(): string\n    {\n        return self::API_METHOD;\n    }\n";
        $out .= "\n    /** @internal */\n";
        if ($command->method === 'broadcast') {
            // Its result is per channel: Client::broadcast and Batch::add decode it.
            $out .= "    public static function decodeResult(mixed \$v, string \$path): never\n    {\n";
            $out .= "        throw new \\LogicException('a broadcast result is decoded with its channels');\n    }\n";
        } else {
            $out .= "    public static function decodeResult(mixed \$v, string \$path): {$result}\n    {\n";
            $out .= "        return {$result}::fromWire(\$v, \$path);\n    }\n";
        }
    }

    // toJson: the message as JSON, zero values left out, payloads spliced in.
    $out .= "\n    /**\n     * The message as Centrifugo reads it: JSON, fields at their zero value\n";
    $out .= "     * left out. \$path prefixes the field names in error messages.\n     */\n";
    $out .= "    public function toJson(string \$path = ''): string\n    {\n";
    if ($m->fields === []) {
        $out .= "        return '{}';\n";
    } else {
        $out .= "        \$p = [];\n";
        foreach ($m->fields as $f) {
            foreach (encoder($f) as $line) {
                $out .= "        {$line}\n";
            }
        }
        $out .= "\n        return '{' . implode(',', \$p) . '}';\n";
    }
    $out .= "    }\n";

    $out .= "\n    /** The message as toJson gives it, for a json_encode of your own. */\n";
    $out .= "    public function jsonSerialize(): RawJson\n    {\n        return new RawJson(\$this->toJson());\n    }\n";

    // fromWire: from the objects json_decode gives.
    $out .= "\n    /** @internal */\n";
    $out .= "    public static function fromWire(mixed \$v, string \$path): static\n    {\n";
    if ($m->fields === []) {
        $out .= "        Decode::object(\$v, \$path);\n\n        return new static();\n";
    } else {
        $out .= "        \$d = Decode::object(\$v, \$path);\n\n        return new static(\n";
        foreach ($m->fields as $f) {
            $out .= '            ' . camel($f->name) . ': ' . decoder($f) . ",\n";
        }
        $out .= "        );\n";
    }
    return $out . "    }\n}\n";
}

// Parameter names the methods take besides a request's fields.
const OWN_PARAMS = ['timeout', 'maxAttempts', 'attemptTimeout', 'onAttemptError'];

const BROADCAST_DOC = <<<'DOC'
    Channels succeed or fail on their own. It returns when every channel got
    the publication. When Centrifugo carried the broadcast out and one or more
    channels failed - up to all of them - it throws
    BroadcastFailedChannelsException, whose $result holds every channel's
    outcome. Any other exception means it failed as a whole: no channel got a
    reply. After a timeout or a network error Centrifugo may still have
    published it.

    To go on despite some failed channels:

        try {
            $client->broadcast(channels: $channels, data: $data);
        } catch (BroadcastFailedChannelsException $e) {
            $logger->warning('broadcast failed in some channels', ['failed' => $e->result->failed]);
        }

    Retry it with broadcastWithRetry, which sends again only the channels which
    may still succeed, with one $idempotencyKey.
    DOC;

const BROADCAST_RETRY_DOC = <<<'DOC'
    Broadcasts as broadcast does, and retries the channels which failed for a
    temporary reason - see Retry::retryable - up to $maxAttempts (2 by default:
    one retry).

    - Only the channels which may still succeed are sent again; when only
      channels which failed for good are left, it stops.
    - Every attempt carries the same $idempotencyKey - made for the call when
      none is given - so that a channel which got the publication in an
      earlier attempt does not get it again. The memory, Redis and PostgreSQL
      brokers keep keys; the NATS broker ignores them, and a retry may publish
      again.
    - The result holds every channel's last outcome, and the key: retrying
      later with it publishes only into the channels which did not get it.

    $timeout, when set, bounds the whole call, waits included; $attemptTimeout
    - requestTimeout by default - bounds each attempt. Waits block the calling
    request: in a web request, set a short $timeout, and retry for longer from
    a job queue, with an $idempotencyKey of its own.

    $onAttemptError is called after an attempt which failed in a way a retry
    may fix, except the last, with a BroadcastAttempt. It returns the seconds
    to wait before the next attempt, or null for the default wait -
    Retry::exponentialBackoff(0.1, 5.0) of the attempt - and may log or count
    meanwhile. To stop, it throws: its exception propagates as it is - the
    BroadcastAttempt it was given holds the attempt's error and every channel's
    outcome so far. The wait never outlasts the call's timeout.

    It throws as broadcast does.
    DOC;

/** Lines of a heredoc constant, its indentation gone. */
function lines(string $text): array
{
    return explode("\n", $text);
}

/**
 * The parameters of a request's method, a field each, and the expression
 * building the request from them.
 *
 * @return array{list<string>, list<string>, string} @param lines, the parameters, the request
 */
function fieldParams(Command $c): array
{
    $docs = [];
    $required = [];
    $params = [];
    $args = [];
    foreach ($c->request->fields as $f) {
        $name = camel($f->name);
        if (\in_array($name, OWN_PARAMS, true) || $name === 'this') {
            throw new \RuntimeException("api.proto: {$c->request->name}.{$f->name} would be the method's own \${$name} parameter");
        }
        [$type, $docType, $default] = fieldType($f);
        if (required($f)) {
            $docType = str_replace('|null', '', $docType);
        }
        $text = docText(fieldDoc($c->request, $f));
        $docs[] = "@param {$docType} \${$name}" . ($text !== [] ? ' ' . array_shift($text) : '');
        foreach ($text as $t) {
            $docs[] = '    ' . $t;
        }
        if (required($f)) {
            // Required first: an optional parameter before a required one is
            // deprecated. Named arguments make the order no part of the API.
            $required[] = ltrim($type, '?') . " \${$name}";
        } else {
            $params[] = "{$type} \${$name} = {$default}";
        }
        $args[] = "{$name}: \${$name}";
    }
    $params = [...$required, ...$params];

    // One argument a line when they don't fit one: the body is indented by 8.
    $request = \count($args) <= 2
        ? "new {$c->request->name}(" . implode(', ', $args) . ')'
        : "new {$c->request->name}(\n            " . implode(",\n            ", $args) . ",\n        )";

    return [$docs, $params, $request];
}

function method(array $doc, string $signature, array $params, string $returns, string $body): string
{
    $out = "\n" . docblock($doc, '    ');
    if ($params === []) {
        return $out . "    {$signature}(): {$returns}\n    {\n        {$body}\n    }\n";
    }
    $out .= "    {$signature}(\n";
    foreach ($params as $p) {
        $out .= "        {$p},\n";
    }

    return $out . "    ): {$returns} {\n        {$body}\n    }\n";
}

/** The imports of a trait of methods: the request classes and the result types. */
function methodsHeader(array $cmds, array $uses): string
{
    $out = \sprintf(HEADER, 'api.proto', 'Centrifugal\\Phpcent') . "\n";
    foreach ($cmds as $c) {
        $uses[] = 'Centrifugal\\Phpcent\\Internal\\' . $c->request->name;
    }
    $uses = array_unique($uses);
    sort($uses);
    foreach ($uses as $u) {
        $out .= "use {$u};\n";
    }

    return $out . "\n";
}

function emitClientMethods(array $cmds): string
{
    $out = methodsHeader($cmds, ['Centrifugal\\Phpcent\\Exception\\CentException', 'Centrifugal\\Phpcent\\Internal\\Limits', 'Centrifugal\\Phpcent\\Internal\\Request']);
    $out .= "/**\n * The server API methods of Client, one per method of api.proto.\n *\n * @internal\n */\n";
    $out .= "trait ClientMethods\n{\n";
    $out .= "    /**\n     * @template T\n     *\n     * @param Request<T> \$request\n     *\n     * @return T\n     */\n";
    $out .= "    abstract private function invoke(Request \$request, ?float \$timeout): mixed;\n\n";
    $out .= "    abstract private function sendBroadcast(BroadcastRequest \$request, ?float \$timeout): BroadcastResult;\n\n";
    $out .= "    /** @param ?callable(BroadcastAttempt): ?float \$onAttemptError */\n";
    $out .= "    abstract private function retryBroadcast(BroadcastRequest \$request, int \$maxAttempts, ?float \$attemptTimeout, ?callable \$onAttemptError, ?float \$timeout): BroadcastResult;\n";
    $timeoutDoc = ['@param ?float $timeout Seconds bounding the call: requestTimeout when null. With an',
        '    httpClient of your own, its timeouts bound the request instead.'];
    foreach ($cmds as $c) {
        [$fieldDocs, $params, $request] = fieldParams($c);
        $name = camel($c->method);
        $doc = methodDoc($c);
        if ($c->method === 'broadcast') {
            $doc = [...$doc, '', ...lines(BROADCAST_DOC)];
        }
        $doc = [...$doc, '', ...$fieldDocs, ...$timeoutDoc, '', '@throws CentException'];
        $returns = $c->method === 'broadcast' ? 'BroadcastResult' : $c->result;
        $call = $c->method === 'broadcast' ? "\$this->sendBroadcast({$request}, \$timeout)" : "\$this->invoke({$request}, \$timeout)";
        $out .= method($doc, "public function {$name}", [...$params, '?float $timeout = null'], $returns, "return {$call};");
        if ($c->method === 'broadcast') {
            $doc = [...lines(BROADCAST_RETRY_DOC), '', ...$fieldDocs,
                '@param int $maxAttempts Attempts at most, the first included.',
                '@param ?float $attemptTimeout Seconds bounding each attempt: requestTimeout when null.',
                '@param ?callable(BroadcastAttempt): ?float $onAttemptError Called after an attempt',
                '    which failed in a way a retry may fix, except the last; returns the',
                '    seconds to wait before the next attempt, or null for the default wait.',
                '@param ?float $timeout Seconds bounding the whole call, waits included: no',
                '    bound but each attempt\'s when null.',
                '', '@throws CentException'];
            $own = ['int $maxAttempts = Limits::MAX_ATTEMPTS', '?float $attemptTimeout = null', '?callable $onAttemptError = null', '?float $timeout = null'];
            $out .= method($doc, 'public function broadcastWithRetry', [...$params, ...$own], 'BroadcastResult', "return \$this->retryBroadcast({$request}, \$maxAttempts, \$attemptTimeout, \$onAttemptError, \$timeout);");
        }
    }

    return $out . "}\n";
}

function emitBatchMethods(array $cmds): string
{
    $out = methodsHeader($cmds, ['Centrifugal\\Phpcent\\Internal\\Request']);
    $out .= "/**\n * The commands a Batch takes, one per method of api.proto.\n *\n * @internal\n */\n";
    $out .= "trait BatchMethods\n{\n";
    $out .= "    /**\n     * @template T\n     *\n     * @param Request<T> \$request\n     *\n     * @return Pending<T>\n     */\n";
    $out .= "    abstract private function add(Request \$request): Pending;\n";
    foreach ($cmds as $c) {
        [$fieldDocs, $params, $request] = fieldParams($c);
        $result = $c->method === 'broadcast' ? 'BroadcastResult' : $c->result;
        $doc = methodDoc($c);
        $doc[] = '';
        $doc[] = 'Adds the command to the batch: its Pending holds the result once the';
        $doc[] = 'batch is sent' . ($c->method === 'broadcast' ? ', and throws BroadcastFailedChannelsException' : '.');
        if ($c->method === 'broadcast') {
            $doc[] = 'when any channel failed.';
        }
        $doc = [...$doc, '', ...$fieldDocs, '', "@return Pending<{$result}>"];
        $out .= method($doc, 'public function ' . camel($c->method), $params, 'Pending', "return \$this->add({$request});");
    }

    return $out . "}\n";
}

function emitCommandMethods(array $cmds): string
{
    $out = methodsHeader($cmds, ['Centrifugal\\Phpcent\\Exception\\InvalidRequestException', 'Centrifugal\\Phpcent\\Internal\\Request']);
    $out .= "/**\n * The commands of Command, one per method of api.proto.\n *\n * @internal\n */\n";
    $out .= "trait CommandMethods\n{\n";
    $out .= "    /** @param Request<mixed> \$request */\n";
    $out .= "    abstract private static function of(Request \$request): self;\n";
    foreach ($cmds as $c) {
        [$fieldDocs, $params, $request] = fieldParams($c);
        $doc = methodDoc($c);
        $doc[] = '';
        $doc[] = 'The command making the call, checked as a Client checks it.';
        $doc = [...$doc, '', ...$fieldDocs, '', '@throws InvalidRequestException'];
        $out .= method($doc, 'public static function ' . camel($c->method), $params, 'self', "return self::of({$request});");
    }

    return $out . "}\n";
}

function emitMethods(array $cmds): string
{
    $out = \sprintf(HEADER, 'api.proto', 'Centrifugal\\Phpcent\\Internal') . "\n";
    $out .= "/**\n * Every API method, batch included, and whether only Centrifugo PRO has it.\n *\n * @internal\n */\n";
    $out .= "final class Methods\n{\n    public const array PRO = [\n        'batch' => false,\n";
    foreach ($cmds as $c) {
        $out .= "        '{$c->method}' => " . ($c->proOnly ? 'true' : 'false') . ",\n";
    }

    return $out . "    ];\n}\n";
}

/**
 * The proxy messages the methods which are not streaming use, directly or
 * through their fields - but the envelopes, which the handlers build, Error and
 * Disconnect, which are exceptions, and the wrappers.
 *
 * @return list<ProtoMessage>
 */
function proxyMessages(Proto $s): array
{
    $used = [];
    $visit = static function (string $name) use (&$visit, &$used, $s): void {
        $m = $s->byName[$name] ?? null;
        if ($m === null || isset($used[$name])) {
            return;
        }
        $used[$name] = true;
        foreach ($m->fields as $f) {
            $visit($f->type);
        }
    };
    $skip = array_fill_keys(['Error', 'Disconnect', ...array_keys(WRAPPERS)], true);
    foreach ($s->methods as $rpc) {
        if (!$rpc->streaming) {
            $visit($rpc->request);
            $visit($rpc->response);
            $skip[$rpc->response] = true;
        }
    }

    return array_values(array_filter($s->messages, static fn(ProtoMessage $m): bool => isset($used[$m->name]) && !isset($skip[$m->name])));
}

/** @return array<string, string> generated file path => code */
function generate(): array
{
    $files = [];
    global $schema;
    $api = $schema = Proto::parse((string) file_get_contents(ROOT . '/proto/api.proto'), 'api.proto');
    $cmds = commands($api);
    $skip = skipped($api);
    $byRequest = [];
    foreach ($cmds as $c) {
        $byRequest[$c->request->name] = $c;
    }
    foreach ($api->messages as $m) {
        if (!isset($skip[$m->name])) {
            $command = $byRequest[$m->name] ?? null;
            $files[($command !== null ? 'Internal/' : '') . "{$m->name}.php"] = emitMessage($m, 'Centrifugal\\Phpcent' . ($command !== null ? '\\Internal' : ''), 'api.proto', 'server API', $command);
        }
    }
    $files['ClientMethods.php'] = emitClientMethods($cmds);
    $files['BatchMethods.php'] = emitBatchMethods($cmds);
    $files['CommandMethods.php'] = emitCommandMethods($cmds);
    $files['Internal/Methods.php'] = emitMethods($cmds);

    $proxy = $schema = Proto::parse((string) file_get_contents(ROOT . '/proto/proxy.proto'), 'proxy.proto');
    foreach (proxyMessages($proxy) as $m) {
        $files["Proxy/{$m->name}.php"] = emitMessage($m, 'Centrifugal\\Phpcent\\Proxy', 'proxy.proto', 'proxy protocol', null);
    }
    ksort($files);

    return $files;
}

/** Writes files under dir, formatted with the project's php-cs-fixer rules. */
function writeFormatted(array $files, string $dir): void
{
    foreach ($files as $path => $code) {
        $full = "{$dir}/{$path}";
        if (!is_dir(\dirname($full))) {
            mkdir(\dirname($full), 0o777, true);
        }
        file_put_contents($full, $code);
    }
    $cmd = [PHP_BINARY, ROOT . '/vendor/bin/php-cs-fixer', 'fix', '--quiet', '--config=' . ROOT . '/.php-cs-fixer.dist.php', '--path-mode=override', '--using-cache=no', $dir];
    $proc = proc_open($cmd, [1 => ['pipe', 'w'], 2 => ['pipe', 'w']], $pipes);
    if (!\is_resource($proc)) {
        throw new \RuntimeException('cannot run php-cs-fixer');
    }
    $err = stream_get_contents($pipes[1]) . stream_get_contents($pipes[2]);
    if (proc_close($proc) !== 0) {
        throw new \RuntimeException("php-cs-fixer failed: {$err}");
    }
}

/** @return array<string, string> relative path => contents, of every PHP file under dir */
function readTree(string $dir): array
{
    $out = [];
    if (!is_dir($dir)) {
        return $out;
    }
    $it = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($dir, \FilesystemIterator::SKIP_DOTS));
    foreach ($it as $file) {
        if ($file->isFile() && $file->getExtension() === 'php') {
            $out[substr($file->getPathname(), \strlen($dir) + 1)] = (string) file_get_contents($file->getPathname());
        }
    }
    ksort($out);

    return $out;
}

function removeTree(string $dir): void
{
    if (!is_dir($dir)) {
        return;
    }
    $it = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($dir, \FilesystemIterator::SKIP_DOTS), \RecursiveIteratorIterator::CHILD_FIRST);
    foreach ($it as $file) {
        $file->isDir() ? rmdir($file->getPathname()) : unlink($file->getPathname());
    }
    rmdir($dir);
}

function main(array $argv): int
{
    $check = \in_array('--check', $argv, true);
    $tmp = sys_get_temp_dir() . '/phpcent-gen-' . bin2hex(random_bytes(6));
    try {
        writeFormatted(generate(), $tmp);
        $fresh = readTree($tmp);
        $target = ROOT . '/generated';
        if ($check) {
            $current = readTree($target);
            if ($current !== $fresh) {
                $stale = array_keys(array_diff_assoc($fresh, $current) + array_diff_key($current, $fresh));
                fwrite(STDERR, 'stale generated code: ' . implode(', ', \array_slice($stale, 0, 10)) . ": run `composer generate`\n");

                return 1;
            }

            return 0;
        }
        removeTree($target);
        foreach ($fresh as $path => $code) {
            $full = "{$target}/{$path}";
            if (!is_dir(\dirname($full))) {
                mkdir(\dirname($full), 0o777, true);
            }
            file_put_contents($full, $code);
        }

        return 0;
    } finally {
        removeTree($tmp);
    }
}

exit(main($argv));
